"""What `wikiloop build` writes for a wiki with on-call: the mod with the plugin's name, its
config, and the skill rendered from the wiki's own `[oncall]`."""
from __future__ import annotations

import re
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from helpers import ROOT  # noqa: E402
from test_defaults import WIKI  # noqa: E402

from oncall import build  # noqa: E402
from wikiloop import config as wiki_config  # noqa: E402


def generated() -> dict:
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        (root / "wikiloop.toml").write_text(WIKI + (ROOT / "oncall" / "example.toml").read_text())
        cfg = wiki_config.load(root)
        return build.generate(cfg, root)


def frontmatter(text: str) -> dict:
    head = text.split("\n---\n", 1)[0]
    return dict(re.findall(r"^([a-z-]+):\s*(.*)$", head, re.M))


class GenerateTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.files = generated()

    def test_every_on_call_file_is_generated(self):
        self.assertEqual(sorted(self.files), [
            "hooks/oncall/config.ts", "hooks/oncall/register.tsx", "hooks/oncall/state.d.ts",
            "skills/howto-oncall-watch/SKILL.md", "skills/howto-oncall-watch/references/checks.md",
        ])

    def test_the_mod_carries_the_plugin_name_as_a_literal(self):
        for path in ("hooks/oncall/register.tsx", "hooks/oncall/state.d.ts"):
            self.assertNotIn(build.PLACEHOLDER, self.files[path])
            self.assertNotIn(build.COMMAND_PLACEHOLDER, self.files[path])

        self.assertIn("{ plugin: 'acme-wiki', key: 'snapshot' }", self.files["hooks/oncall/register.tsx"])
        self.assertIn("on('command.run', { command: 'oncall' }", self.files["hooks/oncall/register.tsx"])
        self.assertIn("'acme-wiki': {", self.files["hooks/oncall/state.d.ts"])

    def test_the_config_holds_what_the_screen_needs(self):
        config_ts = self.files["hooks/oncall/config.ts"]

        self.assertTrue(config_ts.startswith("// Generated by wikiloop build"))
        self.assertIn('export const COMMAND = "oncall"', config_ts)
        self.assertIn('export const STATE_PATH = ".cache/acme-wiki/oncall/state.json"', config_ts)
        self.assertIn('"title": "Resolved, last 6h"', config_ts)
        self.assertIn("acme-wiki:howto-oncall-watch", config_ts)
        self.assertIn('export const TIER_RANK: Record<string, number> = {"core": 2, "standard": 1}', config_ts)

    def test_the_skill_is_rendered_and_passes_the_wiki_rules(self):
        skill = self.files["skills/howto-oncall-watch/SKILL.md"]
        fields = frontmatter(skill)

        self.assertTrue(skill.startswith("---\nname: howto-oncall-watch\n"))
        self.assertTrue(skill.split("\n---\n", 1)[1].startswith("<!-- Generated by wikiloop build"))
        self.assertEqual(fields["generated"], "wikiloop")
        self.assertLessEqual(len(skill.split("description: >-\n", 1)[1].split("\n")[0].strip()), 250)
        self.assertLessEqual(len(skill.splitlines()), 150)
        self.assertIn("/oncall/watch.py --once", skill)

        for path, text in self.files.items():
            if not path.startswith("skills/"):
                continue
            self.assertNotIn("{{", text, path)
            self.assertNotIn("~/", text, path)
            self.assertIsNone(re.search(r"(?<![\d.])(?:\d{1,3}\.){3}\d{1,3}(?![\d.])", text), path)

    def test_checks_lists_the_wiki_probes_and_sources(self):
        checks = self.files["skills/howto-oncall-watch/references/checks.md"]

        self.assertIn("| `queue-stalled` |", checks)
        self.assertIn("| `ext:regions` |", checks)
        self.assertIn("| `restarts` |", checks)


if __name__ == "__main__":
    unittest.main()
