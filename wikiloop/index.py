"""INDEX.md: one table row per skill, grouped by the name prefixes in `[skills] groups`, then the
maintainer skills, which load only in a session opened in the wiki repo."""
from __future__ import annotations

from pathlib import Path

from wikiloop.lint import MAINTAINER_SKILLS, parse_frontmatter

HEADER = "| Skill | Answers | Owner | Verified | References |\n|---|---|---|---|---|"
FOOTER = "INDEX.footer.md"
MAINTAINER_TITLE = "Maintaining the wiki: in this repo's `.claude/skills/`, not shipped in the plugin"


def skill_files(root: Path, base: str, overlay: dict[str, str]) -> dict[str, dict]:
    """skill -> {"text": SKILL.md, "refs": [names]} under `base`, from disk with `overlay` (path -> content) on top."""
    skills: dict[str, dict] = {}
    for skill_md in sorted((root / base).glob("*/SKILL.md")):
        refs = {p.name for p in (skill_md.parent / "references").glob("*.md")}
        skills[skill_md.parent.name] = {"text": skill_md.read_text(), "refs": refs}

    depth = len(Path(base).parts)
    for path, content in overlay.items():
        parts = Path(path).parts
        if parts[:depth] != Path(base).parts or len(parts) < depth + 2:
            continue

        name, rest = parts[depth], parts[depth + 1:]
        entry = skills.setdefault(name, {"text": "", "refs": set()})
        if rest == ("SKILL.md",):
            entry["text"] = content
        elif len(rest) == 2 and rest[0] == "references" and rest[1].endswith(".md"):
            entry["refs"].add(rest[1])
    return skills


def row(base: str, name: str, entry: dict) -> str:
    fm = parse_frontmatter(entry["text"]) or {}
    refs = ", ".join(sorted(entry["refs"])) or "—"
    return (f"| [{name}]({base}/{name}/SKILL.md) | {fm.get('description', '')} | "
            f"{fm.get('owner', '')} | {fm.get('last-verified', '')} | {refs} |")


def build(root: Path, cfg: dict, overlay: dict[str, str]) -> str:
    groups = cfg["skills"]["groups"]
    rows: dict[str, list[str]] = {g["title"]: [] for g in groups}
    other: list[str] = []

    for name, entry in sorted(skill_files(root, "skills", overlay).items()):
        group = next((g["title"] for g in groups if name.startswith(g["prefix"])), None)
        (rows[group] if group else other).append(row("skills", name, entry))

    maintainer = [row(MAINTAINER_SKILLS, name, entry)
                  for name, entry in sorted(skill_files(root, MAINTAINER_SKILLS, overlay).items())]

    out = ["# Index", "", "<!-- Generated by wikiloop build; do not edit by hand. -->",
           "Pick the skill whose description matches the task, open its `SKILL.md`, follow its reference table.", ""]
    for title, group_rows in [*rows.items(), ("Other", other), (MAINTAINER_TITLE, maintainer)]:
        if group_rows:
            out += [f"## {title}", "", HEADER, *group_rows, ""]

    footer = root / FOOTER
    if footer.is_file():
        out += [footer.read_text().rstrip(), ""]
    return "\n".join(out)
