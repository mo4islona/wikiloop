"""`wikiloop build`: compile a wiki's config, guides and the core templates into its plugin.

    wikiloop build            # write every generated file, remove the ones no longer generated
    wikiloop build --check    # exit 1 if a generated file is missing, changed or stale
    wikiloop build --strict   # also fail on an override written against an older core section

Generated: the plugin and marketplace manifests, `hooks/hooks.json`, `hooks/wikiloop.json` (the
resolved config the hooks read), the `wiki-*` skills, the maintainer skill under `.claude/`,
CONTRIBUTING.md, AGENTS.md, INDEX.md, and the on-call files when `[oncall]` is enabled. The list
of what the last build wrote lives in `hooks/wikiloop.json`, so a file that stops being
generated is removed, never left behind to drift.
"""
from __future__ import annotations

import json
import shlex
from pathlib import Path

from wikiloop import index
from wikiloop.config import CORE, RESOLVED_PATH
from wikiloop.render import Guides, render_text

TEMPLATES = CORE / "templates"
NOTE = "Generated by wikiloop build. Edit wikiloop.toml or guides/, not this file."
# Template tree -> where it lands in the wiki repo. The tree says who sees a file: `plugin` ships
# to every session with the plugin, `maintainer` only to sessions opened in a clone of the wiki
# (its skills need the clone), `repo` is the wiki's own docs.
LAYOUT = {
    "plugin/": "",
    "maintainer/": ".claude/",
    "repo/": "",
}
# Output paths built only on a condition.
CONDITIONAL = {
    "skills/wiki-report-session/": lambda cfg: cfg["report_session"]["kind"] != "none",
}


# Tool calls the tracker reads: the rest cannot be an investigation step or a filed candidate.
TRACKED_TOOLS = "Bash|Skill|mcp__.*"
CODEX_HOOKS = "hooks/codex-hooks.json"


def hook_command(cfg: dict, script: str) -> dict:
    core = cfg["core"]["path"]
    command = f'python3 "${{CLAUDE_PLUGIN_ROOT}}/{core}/hooks/{script}" "${{CLAUDE_PLUGIN_ROOT}}/{RESOLVED_PATH}"'
    return {"type": "command", "command": command, "timeout": 10 if script == "stop.py" else 5}


def hook_events(cfg: dict) -> dict:
    """The same events and scripts for both agents: Codex sends Claude Code's fields and sets
    CLAUDE_PLUGIN_ROOT for plugin hooks."""
    return {
        "SessionStart": [{"hooks": [hook_command(cfg, "session_start.py")]}],
        "UserPromptSubmit": [{"hooks": [hook_command(cfg, "track.py")]}],
        "PreToolUse": [{"matcher": "Bash", "hooks": [hook_command(cfg, "candidate_gate.py")]}],
        "PostToolUse": [{"matcher": TRACKED_TOOLS, "hooks": [hook_command(cfg, "track.py")]}],
        "Stop": [{"hooks": [hook_command(cfg, "stop.py")]}],
    }


def manifests(cfg: dict) -> dict[str, str]:
    wiki = cfg["wiki"]
    plugin = {"name": wiki["plugin"], "description": wiki["description"]}
    hooks: dict = {"hooks": hook_events(cfg)}

    if cfg["oncall"].get("enabled"):
        from oncall import build as oncall_build

        plugin["types"] = oncall_build.TYPES
        hooks["modules"] = [oncall_build.MODULE]

    # Codex reads its own manifest; its hooks file carries no Claude Code module.
    codex_plugin = {"name": wiki["plugin"], "description": wiki["description"],
                    "skills": "./skills/", "hooks": f"./{CODEX_HOOKS}"}

    marketplace = {
        "name": wiki["plugin"],
        "owner": {"name": wiki["owner"]},
        "plugins": [{"name": wiki["plugin"], "source": "./", "description": wiki["description"]}],
    }
    return {
        ".claude-plugin/plugin.json": dump(plugin),
        ".claude-plugin/marketplace.json": dump(marketplace),
        ".codex-plugin/plugin.json": dump(codex_plugin),
        "hooks/hooks.json": dump(hooks),
        CODEX_HOOKS: dump({"hooks": hook_events(cfg)}),
    }


def dump(data: dict) -> str:
    return json.dumps(data, indent=2) + "\n"


def with_note(path: str, text: str) -> str:
    """The generated-file note where the format allows one; SKILL.md keeps its frontmatter first,
    a script its shebang."""
    if path.endswith(".sh"):
        shebang, _, rest = text.partition("\n")
        return f"{shebang}\n# {NOTE}\n{rest}"
    if not path.endswith(".md"):
        return text

    note = f"<!-- {NOTE} -->"
    if text.startswith("---\n"):
        end = text.find("\n---\n", 4) + len("\n---\n")
        return text[:end] + note + "\n" + text[end:]
    return note + "\n" + text


def install_steps(cfg: dict) -> str:
    """The wiki's own environment checks, as `step` calls in install.sh."""
    checks = cfg["install"]["checks"]
    if not checks:
        return "# no environment checks configured: [install] checks in wikiloop.toml"

    lines = ["echo", 'echo "recommended (what this wiki\'s skills use)"']
    for check in checks:
        args = [check.get("tier", "recommended"), check["name"], check.get("hint", ""), check["check"]]
        lines.append("step " + " ".join(shlex.quote(a) for a in args))
    return "\n".join(lines)


def templates(cfg: dict, guides: Guides) -> dict[str, str]:
    cfg = {**cfg, "install": {**cfg["install"], "steps": install_steps(cfg)}}
    out = {}
    for path in sorted(p for p in TEMPLATES.rglob("*") if p.is_file() and p.name != ".DS_Store"):
        rel = path.relative_to(TEMPLATES).as_posix()
        tree = next(t for t in LAYOUT if rel.startswith(t))
        target = LAYOUT[tree] + rel[len(tree):]

        skipped = any(target.startswith(prefix) and not wanted(cfg) for prefix, wanted in CONDITIONAL.items())
        if skipped:
            continue

        out[target] = with_note(target, render_text(path.read_text(), cfg, guides))
    return out


def hook_texts(cfg: dict, guides: Guides) -> dict[str, str]:
    """The hooks' texts, rendered now; runtime values ({root}, {n}, ...) stay as placeholders."""
    names = ("session-rule", "session-report", "stop-reason", "gate-reason")
    return {name.replace("-", "_"): render_text(guides.text("hooks", name), cfg) for name in names}


def generate(root: Path, cfg: dict) -> tuple[dict[str, str], list[str]]:
    """Every generated file as {path: content}, and the guide warnings."""
    guides = Guides(root)
    files = {**manifests(cfg), **templates(cfg, guides)}

    if cfg["oncall"].get("enabled"):
        from oncall import build as oncall_build

        files.update(oncall_build.generate(cfg, root))

    # a feature switched off leaves its skills on disk until write() deletes them
    gone = {p for p in previous(root) if p not in files}
    files["INDEX.md"] = index.build(root, cfg, files, gone)

    resolved = {**cfg, "texts": hook_texts(cfg, guides), "generated": sorted([*files, RESOLVED_PATH])}
    files[RESOLVED_PATH] = dump(resolved)
    return files, guides.warnings


def previous(root: Path) -> list[str]:
    try:
        return json.loads((root / RESOLVED_PATH).read_text()).get("generated", [])
    except (OSError, ValueError):
        return []


def diff(root: Path, files: dict[str, str]) -> list[str]:
    problems = []
    for path, content in files.items():
        target = root / path
        if not target.is_file():
            problems.append(f"missing: {path}")
        elif target.read_text() != content:
            problems.append(f"out of date: {path}")

    for path in previous(root):
        if path not in files and (root / path).exists():
            problems.append(f"no longer generated: {path}")
    return problems


def write(root: Path, files: dict[str, str]) -> tuple[list[str], list[str]]:
    stale = [p for p in previous(root) if p not in files]
    for path in stale:
        (root / path).unlink(missing_ok=True)
        remove_empty_parents(root, (root / path).parent)

    changed = []
    for path, content in files.items():
        target = root / path
        if target.is_file() and target.read_text() == content:
            continue

        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content)
        if path.endswith(".sh"):
            target.chmod(0o755)
        changed.append(path)
    return changed, stale


def remove_empty_parents(root: Path, directory: Path) -> None:
    """A skill whose files stopped being generated leaves no empty folder for lint to trip on."""
    while directory != root and directory.is_dir() and not any(directory.iterdir()):
        directory.rmdir()
        directory = directory.parent


def main(root: Path, cfg: dict, argv: list[str]) -> int:
    files, warnings = generate(root, cfg)
    for w in warnings:
        print(f"WARN {w}\n")

    if "--check" in argv:
        problems = diff(root, files)
        for p in problems:
            print(p)
        if problems:
            print("generated files are out of date; run `wikiloop build` and commit the result")
            return 1
        print(f"generated files up to date ({len(files)})")
    else:
        changed, removed = write(root, files)
        for path in changed:
            print(f"wrote {path}")
        for path in removed:
            print(f"removed {path}")
        print(f"build: {len(changed)} changed, {len(removed)} removed, {len(files)} generated")

    if warnings and "--strict" in argv:
        return 1
    return 0
