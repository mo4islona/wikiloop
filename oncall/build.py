"""Generate a wiki's on-call files from its `[oncall]` table.

`wikiloop build` calls `generate` when `[oncall] enabled` is true and writes each returned file
under the wiki root; it names MODULE in hooks/hooks.json and TYPES in plugin.json. The mod is
templated, not configured at run time: a state reference needs the plugin's name as a literal,
and a hooks module imports only .ts files, so the plugin name and every setting the screen
needs are written into the generated files.
"""
from __future__ import annotations

import json
from pathlib import Path

from oncall import defaults
from oncall.engine import span
from wikiloop.render import render_text

MODULE = "./oncall/register.tsx"
TYPES = "./hooks/oncall/state.d.ts"

MOD = Path(__file__).resolve().parent / "mod"
SKILL = Path(__file__).resolve().parent / "skill"
PLACEHOLDER = "__PLUGIN__"
COMMAND_PLACEHOLDER = "__COMMAND__"
HEADER = "// Generated by wikiloop build from wikiloop.toml [oncall]; edit that, not this file."


def generate(cfg: dict, root: Path) -> dict[str, str]:
    out = {f"hooks/oncall/{name}": templated((MOD / name).read_text(), cfg)
           for name in ("register.tsx", "state.d.ts")}
    out["hooks/oncall/config.ts"] = config_ts(cfg)

    with_docs = {**cfg, "oncall_doc": doc_values(cfg)}
    for path in sorted(SKILL.rglob("*.md")):
        out[f"skills/howto-oncall-watch/{path.relative_to(SKILL)}"] = render_text(path.read_text(), with_docs)
    return out


def templated(text: str, cfg: dict) -> str:
    """The literals a module must spell out: the plugin's name and the command it answers."""
    return text.replace(PLACEHOLDER, cfg["wiki"]["plugin"]).replace(COMMAND_PLACEHOLDER, cfg["oncall"]["command"])


def line_label(cfg: dict) -> str:
    return cfg["oncall"]["title"].lower()


def state_path(cfg: dict) -> tuple[bool, str]:
    """(under $HOME, path): where the watcher writes state.json, as the mod reads it."""
    state_dir = cfg["oncall"]["state_dir"] or f"~/.cache/{cfg['wiki']['plugin']}/oncall"
    under_home = state_dir.startswith("~/")
    path = state_dir[2:] if under_home else state_dir
    return under_home, f"{path.rstrip('/')}/state.json"


def config_ts(cfg: dict) -> str:
    oncall = cfg["oncall"]
    plugin = cfg["wiki"]["plugin"]
    t = oncall["thresholds"]
    label = line_label(cfg)
    command = oncall["command"]

    names = [s["name"] for s in oncall["severities"]]
    severities = [{"name": s["name"], "rank": len(names) - i, "color": s.get("color", "")}
                  for i, s in enumerate(oncall["severities"])]
    tiers = {tier: len(oncall["tiers"]) - i for i, tier in enumerate(oncall["tiers"])}
    sections = [{
        "title": s["title"].replace("{resolved_kept}", span(t["resolved_kept"])),
        "status": s["status"], "minSeverity": s["min_severity"], "maxSeverity": s["max_severity"],
        "chronic": s["chronic"], "isNew": s["new"], "style": s["style"], "color": s["color"],
        "limit": s["limit"], "empty": s["empty"], "foldBelow": s["fold_below"],
    } for s in defaults.sections(oncall)]
    under_home, path = state_path(cfg)

    skill = f"{plugin}:howto-oncall-watch"
    start = (f"Start the {label} watch: load the {skill} skill and run its watcher under Monitor, "
             f"as its Quick path says. If a watcher already runs under Monitor in this session, re-arm that one instead.")
    stop = (f"Stop the {label} watch: stop the Monitor task that runs the {skill} watcher in this session, "
            f"and do not re-arm it until /{command} asks. Leave a watcher that another session runs alone.")

    constants = [
        ("COMMAND", command),
        ("TITLE", oncall["title"]),
        ("LINE_LABEL", label),
        ("STATE_UNDER_HOME", under_home),
        ("STATE_PATH", path),
        ("SEVERITIES: SeverityDef[]", severities),
        ("LOUD", oncall["loud"]),
        ("FLOOR", oncall["floor"]),
        ("TIER_RANK: Record<string, number>", tiers),
        ("DEFAULT_ENV", oncall["subject"]["default_env"]),
        ("SECTIONS: SectionDef[]", sections),
        ("DEFAULT_INTERVAL_MS", oncall["interval"] * 1000),
        ("NEW_WINDOW_MS", t["new_window"] * 1000),
        ("CHRONIC_AFTER_MS", t["chronic_after"] * 1000),
        ("RESOLVED_KEPT_MS", t["resolved_kept"] * 1000),
        ("STALE_SLACK_MS", t["stale_slack"] * 1000),
        ("OFF_AFTER_MS", t["off_after"] * 1000),  # no cycle for this long: nobody watches from here
        ("START_GUARD_MS", t["start_guard"] * 1000),  # the model turn, its permission prompt and the first cycle
        ("START_PROMPT", start),
        ("STOP_PROMPT", stop),
    ]

    lines = [HEADER, "import type { SectionDef, SeverityDef } from './state'", ""]
    lines += [f"export const {name} = {json.dumps(value)}" for name, value in constants]
    return "\n".join(lines) + "\n"


def cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def doc_values(cfg: dict) -> dict:
    """Text the skill template needs that is not a plain config value."""
    oncall = cfg["oncall"]
    t = oncall["thresholds"]
    under_home, path = state_path(cfg)

    sources = []
    if oncall["alertmanager"]["url"]:
        sources.append("| `alertmanager` | every active alert, silenced and inhibited ones included (Alertmanager API v2) | "
                       "a silenced alert stays in the report, marked, and never raises a problem's severity |")
    if oncall["probes"]:
        sources.append("| `probes` | the PromQL probes below, one signal per series a query returns | "
                       "a failure that no rule sees, or sees too late |")
    if oncall["restarts"]["enabled"]:
        sources.append(f"| `restarts` | kube-state-metrics: every container restart within {oncall['restarts']['window']} | "
                       "the first restart, while the restart rules still wait for a pattern |")
    for ext in oncall["extensions"]:
        sources.append(f"| `ext:{Path(ext).stem}` | `{ext}` in the wiki | what that module's docstring says |")

    probes = [f"| `{p['name']}` | {cell(p['description']) or '-'} | `{cell(p['query'])}` |"
              for p in defaults.probes(oncall)]
    sections = [s["title"].replace("{resolved_kept}", span(t["resolved_kept"])) for s in defaults.sections(oncall)]

    return {
        "sources_table": "\n".join(sources),
        "probes_table": "\n".join(probes) or "| - | no probes configured | - |",
        "state_dir": ("$HOME/" if under_home else "") + path.rsplit("/", 1)[0],
        "sections_list": ", ".join(f"**{s}**" for s in sections),
        "interval": span(oncall["interval"]),
        "chronic_after": span(t["chronic_after"]),
        "resolved_kept": span(t["resolved_kept"]),
        "flap_quiet": span(t["flap_quiet"]),
        "fleet_gap": span(t["fleet_gap"]),
        "spread_every": span(t["spread_every"]),
        "heartbeat": span(oncall["heartbeat"]) if oncall["heartbeat"] else "never",
        "start_guard": span(t["start_guard"]),
        "off_after": span(t["off_after"]),
    }
